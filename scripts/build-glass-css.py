"""Builds src/glass.css: the Light glass / Dark glass colour scheme.

    python3 scripts/build-glass-css.py

The pages colour themselves with inline styles (cream cards #FDF6EE,
parchment boxes #F2E4D0, dark panels #1A0A00, brown text...). This script
writes CSS rules that match those inline colours (as the browser writes
them, e.g. "background: rgb(253, 246, 238)") and restyle them as glass, so
every page follows the theme without rewriting each component.

Layers (later and more specific wins):
  surface   a cream/parchment/white card            -> frosted glass
  nested    a surface inside another surface         -> a soft inner box (no extra blur)
  modal     the panel of a pop-up (child of the fixed full-screen wrapper)
  overlay   the dim layer behind a pop-up            -> blurred, not brown
  buttons   surface/dark buttons, disabled buttons
  inputs    text boxes and selects
  dark only: dark panels, tints, status colours, text and icon colours
"""
