def bg(*prefixes):
    """Selectors for elements whose inline background starts with a prefix."""
    out = []
    for p in prefixes:
        out += [f'[style^="background: {p}"]', f'[style*="; background: {p}"]',
                f'[style^="background-color: {p}"]', f'[style*="; background-color: {p}"]']
    return out


def col(*prefixes):
    out = []
    for p in prefixes:
        out += [f'[style^="color: {p}"]', f'[style*="; color: {p}"]']
    return out


